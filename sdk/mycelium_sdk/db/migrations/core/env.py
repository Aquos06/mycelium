"""Alembic environment for the core tables (mycelium_sdk.db.core.metadata).

Revisions are autogenerated from that metadata. Three ways in: a service passes an open connection
through config.attributes (mycelium_sdk.db.migrate), the CLI builds an async engine from
DATABASE_URL, or offline mode prints SQL.
"""

from __future__ import annotations

import asyncio
import os

from alembic import context
from sqlalchemy.ext.asyncio import create_async_engine

from mycelium_sdk.db import sqlalchemy_url
from mycelium_sdk.db.core import metadata

config = context.config
target_metadata = metadata


def include_name(name, type_, parent_names) -> bool:
    """Only the default schema: other owners' schemas (memory, ...) have their own trees."""
    if type_ == "schema":
        return name is None
    return True


def run_migrations(connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        include_name=include_name,
        compare_type=True,
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_from_env() -> None:
    engine = create_async_engine(sqlalchemy_url(os.environ["DATABASE_URL"]))
    async with engine.connect() as connection:
        await connection.run_sync(run_migrations)
        await connection.commit()
    await engine.dispose()


if (connection := config.attributes.get("connection")) is not None:
    run_migrations(connection)
elif context.is_offline_mode():
    context.configure(url="postgresql://x", target_metadata=target_metadata, literal_binds=True)
    with context.begin_transaction():
        context.run_migrations()
else:
    asyncio.run(run_from_env())

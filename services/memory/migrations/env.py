"""Alembic environment for memory's index.

Revisions are autogenerated from IndexTables("memory").metadata and name the schema `memory`.
At run time a schema_translate_map turns that into the real target schema, which comes from
config.attributes["schema"] (mycelium_sdk.db.migrate), from `-x schema=...` on the CLI, or defaults
to `memory`. The version table lives in the target schema, so several schemas in one database
(tests, later per-owner databases) each track their own head.
"""

from __future__ import annotations

import asyncio
import os

from alembic import context
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

from memory.index.tables import CANONICAL_SCHEMA, IndexTables, Vector
from mycelium_sdk.db import sqlalchemy_url

config = context.config
schema = config.attributes.get("schema") or context.get_x_argument(as_dictionary=True).get("schema") or CANONICAL_SCHEMA
config.attributes["schema"] = schema
target_metadata = IndexTables(CANONICAL_SCHEMA).metadata


def include_name(name, type_, parent_names) -> bool:
    """Autogenerate looks only at this owner's schema, never at the core tables next door."""
    if type_ == "schema":
        return name == schema
    return True


def render_item(type_, obj, autogen_context):
    if type_ == "type" and isinstance(obj, Vector):
        autogen_context.imports.add("from memory.index.tables import Vector")
        return f"Vector({obj.dim})"
    return False


def run_migrations(connection) -> None:
    translate = {CANONICAL_SCHEMA: schema} if schema != CANONICAL_SCHEMA else {}
    connection = connection.execution_options(schema_translate_map=translate)
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        version_table_schema=schema,
        include_schemas=True,
        include_name=include_name,
        render_item=render_item,
        compare_type=True,
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_from_env() -> None:
    dsn = os.environ.get("MEMORY_DATABASE_URL") or os.environ["DATABASE_URL"]
    engine = create_async_engine(sqlalchemy_url(dsn))
    async with engine.connect() as connection:
        await connection.execute(text(f'CREATE SCHEMA IF NOT EXISTS "{schema}"'))
        await connection.commit()
        await connection.run_sync(run_migrations)
        await connection.commit()
    await engine.dispose()


if (connection := config.attributes.get("connection")) is not None:
    run_migrations(connection)
elif context.is_offline_mode():
    context.configure(
        url="postgresql://x", target_metadata=target_metadata, version_table_schema=schema, literal_binds=True
    )
    with context.begin_transaction():
        context.run_migrations()
else:
    asyncio.run(run_from_env())
